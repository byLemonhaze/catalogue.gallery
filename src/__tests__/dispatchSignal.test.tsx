import {afterEach,beforeEach,expect,it,vi} from 'vitest';
import {act,cleanup,fireEvent,render,screen} from '@testing-library/react';
import {MemoryRouter} from 'react-router-dom';
import {DispatchSignal} from '../components/DispatchSignal';
const post={id:'issue',slug:'2026-11-11',title:'Daily edition',publishedAt:'2026-11-11',summary:'First story',items:[{number:1,headline:'First real headline',body:''},{number:2,headline:'Second real headline',body:''}]};
beforeEach(()=>{vi.useFakeTimers();vi.stubGlobal('matchMedia',vi.fn(()=>({matches:false,addEventListener:vi.fn(),removeEventListener:vi.fn()})));});
afterEach(()=>{cleanup();vi.useRealTimers();vi.unstubAllGlobals();});
const mount=()=>render(<MemoryRouter><DispatchSignal post={post}/></MemoryRouter>);
const activeText=()=>Array.from(document.querySelectorAll('.signal-counter-text [data-shown=true]')).map(node=>node.textContent).join(' ');
const indexText=()=>Array.from(document.querySelectorAll('.signal-index li>span:last-child')).map(node=>node.textContent);
it('reveals words and advances every headline, omits the duplicate static index, then loops',()=>{
    mount();
    const link=screen.getByRole('link',{name:'Read the edition: Daily edition'});
    expect(link).toHaveAttribute('href','/dispatch/2026-11-11/');
    expect(activeText()).toBe('');
    expect(document.querySelector('.signal-index')).toBeNull();
    act(()=>vi.advanceTimersByTime(240));
    expect(activeText()).toBe('First');
    act(()=>vi.advanceTimersByTime(600));
    expect(activeText()).toBe('First real headline');
    act(()=>vi.advanceTimersByTime(2480));
    expect(document.querySelector('.signal-mast')).toHaveTextContent('02 / 02');
    expect(activeText()).toBe('');
    act(()=>vi.advanceTimersByTime(880));
    expect(activeText()).toBe('Second real headline');
    act(()=>vi.advanceTimersByTime(4160));
    expect(document.querySelector('.signal-mast')).toHaveTextContent('01 / 02');
    expect(activeText()).toBe('');
    expect(document.querySelector('.signal-index')).toBeNull();
    expect(link).toHaveAccessibleDescription('First real headline. Second real headline');
});
it('finishes revealing words and holds the current story on keyboard focus, then resumes on blur',()=>{
    mount();
    const link=screen.getByRole('link');
    fireEvent.focus(link);
    act(()=>vi.advanceTimersByTime(12000));
    expect(activeText()).toBe('First real headline');
    expect(document.querySelector('.signal-mast')).toHaveTextContent('01 / 02');
    fireEvent.blur(link);
    act(()=>vi.advanceTimersByTime(2520));
    expect(document.querySelector('.signal-mast')).toHaveTextContent('02 / 02');
});
it('shows the complete edition without word animation when reduced motion is requested',()=>{
    vi.stubGlobal('matchMedia',vi.fn(()=>({matches:true,addEventListener:vi.fn(),removeEventListener:vi.fn()})));
    mount();
    expect(document.querySelector('.signal-counter-stage')).toBeNull();
    expect(indexText()).toEqual(post.items.map(item=>item.headline));
    act(()=>vi.advanceTimersByTime(15000));
    expect(indexText()).toEqual(post.items.map(item=>item.headline));
    expect(document.querySelector('.signal-caret')).toBeNull();
});
it('uses the summary when an edition has no structured headlines',()=>{
    render(<MemoryRouter><DispatchSignal post={{...post,items:[]}}/></MemoryRouter>);
    expect(screen.getByRole('link')).toHaveAccessibleDescription('First story');
    expect(document.querySelector('.signal-mast')).toHaveTextContent('01 / 01');
});
